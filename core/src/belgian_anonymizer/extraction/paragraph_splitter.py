import statistics
from dataclasses import dataclass, field

import pypdfium2 as pdfium
import pypdfium2.raw as pdfium_c
from docling_core.types.doc.base import BoundingBox
from docling_core.types.doc.common.reference import ProvenanceItem
from docling_core.types.doc.document import DoclingDocument
from docling_core.types.doc.items.text import TextItem
from docling_core.types.doc.labels import DocItemLabel

# Width of the space before the next word, as a fraction of the line height
_SPACE_WIDTH_RATIO = 0.25
# Extra vertical space (beyond the usual line spacing) that separates two paragraphs, in points
_PARAGRAPH_EXTRA_GAP = 2.0
# Characters compared to find the start of a paragraph in Docling's text
_NEEDLE_LENGTH = 25
_SPLIT_LABELS = {DocItemLabel.TEXT, DocItemLabel.PARAGRAPH}
# A block narrower than this fraction of the page's text column (address, signature) keeps its lines
_NARROW_BLOCK_RATIO = 0.6
_PARAGRAPH_BREAK = "\n\n"
# Markdown hard line break: the lines stay together in one block
_LINE_BREAK = "  \n"
# Docling normalises these characters (see PageAssembleModel.sanitize_text)
_NORMALISATION = str.maketrans({"’": "'", "‘": "'", "“": '"', "”": '"', "⁄": "/", "•": "·"})


@dataclass(slots=True)
class _Line:
    """A visual line of the PDF page, in PDF coordinates (origin bottom-left)."""

    chars: list[str] = field(default_factory=list)
    left: float = float("inf")
    right: float = float("-inf")
    bottom: float = float("inf")
    top: float = float("-inf")
    first_word_right: float | None = None

    @property
    def text(self) -> str:
        return "".join(self.chars).strip()

    @property
    def height(self) -> float:
        return self.top - self.bottom

    @property
    def has_glyphs(self) -> bool:
        return self.left != float("inf")

    def add(self, char: str, box: tuple[float, float, float, float] | None) -> None:
        # Word spaces are often generated by PDFium without a box: check them before measuring
        if char.isspace() and self.first_word_right is None and self.has_glyphs:
            self.first_word_right = self.right
        if box is not None:
            left, bottom, right, top = box
            self.left, self.right = min(self.left, left), max(self.right, right)
            self.bottom, self.top = min(self.bottom, bottom), max(self.top, top)
        self.chars.append(char)

    def first_word_width(self) -> float:
        return (self.first_word_right if self.first_word_right is not None else self.right) - self.left


class ParagraphSplitter:
    """Splits Docling text blocks that group several paragraphs.

    Docling's layout model sometimes detects consecutive short paragraphs (typically the parties
    of a contract) as one block, and its reading order may merge separate regions (a letter's
    sender, recipient and date) into one item. Each region becomes a paragraph; within a region,
    a line ending well before the right edge of the block, or followed by an unusual vertical gap,
    ends a paragraph. Narrow blocks such as addresses keep every line.
    """

    def split(self, document: DoclingDocument, content: bytes) -> None:
        pdf = pdfium.PdfDocument(content)
        try:
            lines_by_page: dict[int, list[_Line]] = {}
            for item, _level in document.iterate_items():
                if not isinstance(item, TextItem) or item.label not in _SPLIT_LABELS:
                    continue
                regions = self._regions(item)
                if regions is None:
                    continue
                paragraphs: list[str] = []
                for provenance, text in regions:
                    if provenance.page_no not in lines_by_page:
                        lines_by_page[provenance.page_no] = self._read_lines(pdf[provenance.page_no - 1])
                    page_lines = lines_by_page[provenance.page_no]
                    height = document.pages[provenance.page_no].size.height
                    box = provenance.bbox.to_bottom_left_origin(page_height=height)
                    lines = [line for line in page_lines if self._inside(line, box)]
                    breaks = self._breaks(lines, box, self._column_width(page_lines))
                    paragraphs.append(self._insert_breaks(text.strip(), breaks))
                item.text = _PARAGRAPH_BREAK.join(paragraph for paragraph in paragraphs if paragraph)
        finally:
            pdf.close()

    @staticmethod
    def _regions(item: TextItem) -> list[tuple[ProvenanceItem, str]] | None:
        """Splits the item text per source region, using the character span Docling records."""
        if len(item.prov) == 1:
            return [(item.prov[0], item.text)]
        spans = [provenance.charspan for provenance in item.prov]
        contiguous = all(
            0 <= start <= end <= len(item.text) and (index == 0 or start >= spans[index - 1][1])
            for index, (start, end) in enumerate(spans)
        )
        if not item.prov or not contiguous:
            return None
        return [
            (provenance, item.text[start:end])
            for provenance, (start, end) in zip(item.prov, spans, strict=True)
        ]

    @staticmethod
    def _column_width(page_lines: list[_Line]) -> float:
        return max(line.right for line in page_lines) - min(line.left for line in page_lines)

    @staticmethod
    def _read_lines(page: pdfium.PdfPage) -> list[_Line]:
        textpage = page.get_textpage()
        try:
            lines = [_Line()]
            for index in range(textpage.count_chars()):
                char = chr(pdfium_c.FPDFText_GetUnicode(textpage.raw, index))
                if char == "\r":
                    continue
                if char == "\n":
                    lines.append(_Line())
                    continue
                generated = pdfium_c.FPDFText_IsGenerated(textpage.raw, index)
                lines[-1].add(
                    " " if char.isspace() else char,
                    None if generated else textpage.get_charbox(index, loose=True),
                )
            return [line for line in lines if line.has_glyphs and line.text]
        finally:
            textpage.close()
            page.close()

    @staticmethod
    def _inside(line: _Line, box: BoundingBox) -> bool:
        middle = (line.top + line.bottom) / 2
        return box.b <= middle <= box.t and line.left < box.r and line.right > box.l

    @staticmethod
    def _breaks(lines: list[_Line], box: BoundingBox, column_width: float) -> list[tuple[str, str]]:
        """Returns (text of the line starting after the break, separator) pairs."""
        if len(lines) < 2:
            return []
        if box.r - box.l < column_width * _NARROW_BLOCK_RATIO:
            return [(line.text, _LINE_BREAK) for line in lines[1:]]
        gaps = [previous.bottom - line.top for previous, line in zip(lines, lines[1:], strict=False)]
        usual_gap = statistics.median(gaps)
        breaks: list[tuple[str, str]] = []
        for index in range(1, len(lines)):
            previous, line = lines[index - 1], lines[index]
            if previous.text.endswith("-"):
                continue
            space = previous.height * _SPACE_WIDTH_RATIO
            ends_early = previous.right + space + line.first_word_width() < box.r
            spaced_out = gaps[index - 1] > usual_gap + _PARAGRAPH_EXTRA_GAP
            if ends_early or spaced_out:
                breaks.append((line.text, _PARAGRAPH_BREAK))
        return breaks

    @staticmethod
    def _insert_breaks(text: str, breaks: list[tuple[str, str]]) -> str:
        # Docling's text joins the lines with spaces: replace the space before each break position
        cursor = 0
        pieces: list[str] = []
        for line_start, separator in breaks:
            needle = line_start.translate(_NORMALISATION)[:_NEEDLE_LENGTH]
            position = text.find(needle, cursor)
            if position <= 0 or text[position - 1] != " ":
                continue
            pieces.append(text[cursor : position - 1])
            pieces.append(separator)
            cursor = position
        pieces.append(text[cursor:])
        return "".join(pieces)
